package mutation

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
	"time"
)

const subject = `package toy

func Fee(v int) int {
	if v > 10 {
		return v + 2
	}
	return v * 1
}
`

func TestGenerate(t *testing.T) {
	mutants := Generate("toy.go", []byte(subject))
	if len(mutants) != 3 {
		t.Fatalf("mutants = %+v", mutants)
	}
	if mutants[0].Operator != "> -> >=" || mutants[1].Operator != "+ -> -" || mutants[2].Operator != "* -> /" {
		t.Fatalf("operators = %+v", mutants)
	}
	if !strings.Contains(string(mutants[0].Source), "v >= 10") {
		t.Fatalf("mutated source = %s", mutants[0].Source)
	}
	// Test files and generated files are never mutated.
	if got := Generate("toy_test.go", []byte(subject)); got != nil {
		t.Fatal("test files must not be mutated")
	}
	if got := Generate("gen.go", []byte("// Code generated by tool. DO NOT EDIT.\n"+subject)); got != nil {
		t.Fatal("generated files must not be mutated")
	}
}

// TestRunKillsAndSurvives: the test distinguishes the boundary mutant
// (Fee(10): 10 vs 12) and the arithmetic one (Fee(11): 13 vs 9), but cannot
// see `* -> /` (v*1 == v/1 on every tested input) — one honest survivor.
func TestRunKillsAndSurvives(t *testing.T) {
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("go toolchain unavailable")
	}
	dir := t.TempDir()
	write := func(rel, content string) {
		if err := os.WriteFile(filepath.Join(dir, rel), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module example.com/toy\n\ngo 1.24\n")
	write("toy.go", subject)
	write("toy_test.go", `package toy

import "testing"

func TestFee(t *testing.T) {
	if Fee(10) != 10 {
		t.Fatal("boundary")
	}
	if Fee(11) != 13 {
		t.Fatal("above")
	}
	if Fee(5) != 5 {
		t.Fatal("below")
	}
}
`)
	mutants := Generate("toy.go", []byte(subject))
	outcome, err := Run(dir, []string{"./..."}, mutants, Caps{PerMutant: 2 * time.Minute})
	if err != nil {
		t.Fatal(err)
	}
	if outcome.Sites != 3 || outcome.Killed != 2 || outcome.Survived != 1 {
		t.Fatalf("outcome = %+v", outcome)
	}
	if len(outcome.Survivors) != 1 || outcome.Survivors[0].Operator != "* -> /" {
		t.Fatalf("outcome = %+v", outcome)
	}
}
